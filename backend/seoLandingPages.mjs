export function getSeoLandingPath(language, intent) {
  const slug =
    SEO_LANDING_ROUTES[language]?.[intent];

  if (!slug) {
    return null;
  }

  return `/${language}/${slug}/`;
}

export function findSeoLandingRoute(pathname) {
  for (const [language, routes] of Object.entries(
    SEO_LANDING_ROUTES
  )) {
    for (const [intent, slug] of Object.entries(routes)) {
      if (pathname === `/${language}/${slug}/`) {
        return {
          language,
          intent,
          slug
        };
      }
    }
  }

  return null;
}

export function getSeoLandingAlternates(intent) {
  return Object.keys(SEO_LANDING_ROUTES)
    .map(language => ({
      language,
      path: getSeoLandingPath(language, intent)
    }))
    .filter(item => item.path);
}
export function getSeoLandingContent(
  language,
  intent
) {
  if (intent === "photoToVideo") {
    return (
      SEO_LANDING_CONTENT[language]?.photoToVideo ||
      null
    );
  }

  if (intent === "adVideo") {
    return SEO_AD_VIDEO_CONTENT[language] || null;
  }

  if (intent === "ecommerceVideo") {
    return (
      SEO_ECOMMERCE_VIDEO_CONTENT[language] ||
      null
    );
  }

  return null;
}
